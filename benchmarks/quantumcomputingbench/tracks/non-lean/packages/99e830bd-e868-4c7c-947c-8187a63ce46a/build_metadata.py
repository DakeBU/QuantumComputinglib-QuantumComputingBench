#!/usr/bin/env python3
"""Rebuild additive proposal wrappers and inventory; never author review verdicts."""
from __future__ import annotations

import argparse
from collections import Counter, defaultdict
import hashlib
import json
from pathlib import Path
import sys

PACKAGE_ID = "99e830bd-e868-4c7c-947c-8187a63ce46a"
BASE = "6b23dab68c2970062ddfd568ce94bce74b566483"
EXISTING_PROPOSALS = {
    "A1": "68b498d8-84c8-4a48-abca-03b82ed0b017",
    "A4": "59d6331b-0c29-44ed-9922-6acaa4433c42",
    "B1": "62caa401-38cf-44cb-89ec-7c43e9c39211",
    "C1": "843a7a04-3d74-46fd-bce0-a563f13888d7",
}


def read(path):
    return json.loads(path.read_text(encoding="utf-8"))


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def cell(value):
    if not isinstance(value, str):
        value = json.dumps(value, ensure_ascii=False)
    return value.replace("|", "\\|").replace("\n", " ")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", action="store_true",
                        help="Also inventory final files; requires all three actual review reports.")
    args = parser.parse_args()
    package = Path(__file__).resolve().parent
    root = next(p for p in package.parents if (p / "benchmarks/quantumcomputingbench/src/qcb_curriculum.py").is_file())
    rel = lambda p: p.relative_to(root).as_posix()
    sys.path.insert(0, str(root / "benchmarks/quantumcomputingbench/src"))
    from qcb_core import digest
    from qcb_curriculum import load_catalog, core_contract
    catalog, originals, graph = load_catalog()
    baseline = read(package / "evidence/baseline.json")
    if catalog["catalog_hash"] != baseline["catalog_hash"]:
        raise ValueError("Baseline changed: reconcile and re-review before regenerating wrappers.")
    items = [read(f) for f in sorted((package / "qa").glob("[ABC][1-4].json"))]
    if len(items) != 12:
        raise ValueError("Expected twelve complete frozen payloads.")
    reports, reviewed = [], {}
    for group in "ABC":
        path = package / "reviews" / f"{group}-review.json"
        if path.is_file():
            report = read(path)
            reports.append(rel(path))
            for row in report["items"]:
                reviewed[row["slot"]] = {
                    "report_path": rel(path), "report_sha256": sha(path),
                    "reviewer": report["reviewer"], "item_digest": row["item_digest"],
                    "verdict": row["verdict"],
                    "semantic_core_verdict": row["semantic_core_verdict"],
                }
    proposals, contributions = [], []
    inventory = ["# Contribution inventory\n",
                 "Four existing-core views and eight UUID candidates are proposed. No mathematical core is newly admitted. "
                 "The displayed review verdicts are copied from actual content-bound reports, not generated by this script.\n",
                 "| Slot | Target | Core identity | Split | Route | Mathematical review |\n| --- | --- | --- | --- | --- | --- |"]
    overlap = ["# Coverage and overlap at integration\n",
               "The pre-authoring inventory is in `evidence/coverage-audit.md` and its full JSON. "
               "The initial empty PR search is superseded by `OPEN_PR_RECONCILIATION.md`. "
               "These are disclosure and review requests, not semantic admission decisions.\n",
               "| Slot | Existing or candidate | Assessed target | Recorded overlap and split action |\n| --- | --- | --- | --- |"]
    for item in items:
        slot, core = item["slot"], item["core_id"]
        existing = item["contribution_type"] == "existing_core_view"
        pid = EXISTING_PROPOSALS[slot] if existing else item["proposal_id"]
        payload_path = package / "qa" / f"{slot}.json"
        proposal_path = root / "benchmarks/quantumcomputingbench/tracks/non-lean/proposals" / f"{pid}.json"
        evidence = reviewed.get(slot)
        if evidence and evidence["item_digest"] != digest(item):
            raise ValueError("Stale review for " + slot)
        binding = next((r for r in catalog["cores"] if r["core_id"] == core), None)
        if existing and (binding is None or core_contract(item) != core_contract(originals[core])):
            raise ValueError("Existing contract changed: " + slot)
        proposal = {
            "proposal_id": pid, "track": "non-lean", "author": item["author"],
            "core_id": core,
            "admission": "existing_core_view_proposed_not_installed" if existing else "candidate_not_counted",
            "dedup_review_required": True,
            "source_nodes": list(dict.fromkeys(item["target_nodes"] + item["supporting_nodes"])),
            "view_kind": "expanded_derivation_and_rubric" if existing else "derivation",
            "family": item["family"], "split": item["split"],
            "snapshot_id": catalog["snapshot_id"],
            "contract_hash": binding["contract_hash"] if existing else digest(core_contract(item)),
            "base_commit": BASE, "package_id": PACKAGE_ID, "slot": slot,
            "payload_path": rel(payload_path), "payload_sha256": sha(payload_path),
            "item_digest": digest(item), "title": item["title"],
            "mathematical_target": item["mathematical_target"],
            "review_records": [evidence] if evidence else [],
            "status": "authored_with_content_bound_review_pending_maintainer_decision" if evidence else "authored_awaiting_independent_review",
            "count_effect": "zero_until_explicit_admission" if not existing else "view_never_increments_core_count",
            "usage": "public_diagnostic_only; no training or independent held-out clearance",
            "note": "Complete question, assumptions, answer, rubric, boundaries, reasoning map and provenance are in the digest-bound payload. "
                    "Compatibility validation and AI mathematical review do not install this view or admit a new core.",
        }
        if existing:
            proposal["predecessor_item_digest"] = binding["item_digest"]
            proposal["immutable_contract_fields_preserved"] = list(core_contract(item))
            proposal["change_protocol"] = "Additive non-Lean view proposal only; current reader answer and policy unchanged."
        else:
            proposal["proposed_contract"] = core_contract(item)
        write(proposal_path, proposal)
        proposals.append(proposal_path)
        contribution = {k: proposal[k] for k in ["slot", "core_id", "proposal_id", "admission", "status", "family", "split", "snapshot_id", "contract_hash", "item_digest"]}
        contribution.update({"payload_path": rel(payload_path), "proposal_path": rel(proposal_path),
                             "contribution_type": item["contribution_type"],
                             "mathematical_review": evidence or {"verdict": "awaiting_independent_review"},
                             "benchmark_admitted_by_this_package": False})
        contributions.append(contribution)
        d = item["difficulty"]
        route = d.get("provisional_route_band", d.get("construction_band", d.get("D1_D4", {}).get("provisional_route_band", "unspecified")))
        verdict = evidence["verdict"] if evidence else "awaiting independent review"
        inventory.append(f"| {slot} | [{cell(item['title'])}](qa/{slot}.json) | `{core}` | {item['split']} | {route} | {cell(verdict)} |")
        overlap.append(f"| {slot} | {item['contribution_type']} | {cell(item['mathematical_target'])} | {cell(item['overlap'])} |")
    inventory += ["\nD0 records knowledge/contract facets and adds no core. D1–D4 are provisional route annotations, not measured model difficulty. "
                  "No independent D1 item was manufactured to fill a taxonomy cell. The meaningful derivations here use D2–D4.\n",
                  "Author-time pending-review statements remain historical. Exact final review bindings above and in `manifest.json` govern the delivered version.\n"]
    (package / "CONTRIBUTIONS.md").write_text("\n".join(inventory), encoding="utf-8")
    (package / "OVERLAP.md").write_text("\n".join(overlap) + "\n", encoding="utf-8")

    snapshot_path = root / "benchmarks/quantumcomputingbench/manifests/release-v3/snapshot.json"
    snapshot = read(snapshot_path)
    selected = sorted({n for item in items for n in item["target_nodes"] + item["supporting_nodes"]})
    hyperedges = [h for h in snapshot["hyperedges"] if h["id"] in selected or set(h.get("tails", []) + h.get("heads", [])) & set(selected)]
    context_ids = sorted({n for h in hyperedges for n in h.get("tails", []) + h.get("heads", [])} - set(selected))
    source_map = defaultdict(list)
    for item in items:
        for ref in item["source_refs"]:
            source_map[ref["path"]].append({"slot": item["slot"], "anchor": ref["anchor"], "declared_sha256": ref["sha256"]})
        for ref in item["provenance"].get("source_inspection", []):
            source_map[ref["path"]].append({"slot": item["slot"], "inspection": ref})
    sources = []
    for path, uses in sorted(source_map.items()):
        actual = sha(root / path)
        sources.append({"path": path, "sha256_raw": actual,
                        "sha256_lf": hashlib.sha256((root / path).read_text(encoding="utf-8").replace("\r\n", "\n").encode()).hexdigest(),
                        "baseline_commit": BASE, "uses": uses,
                        "fresh_lean_execution": False,
                        "evidence_boundary": "Text inspection and pinned source bytes; no transfer of branch-only claims or new formal verification."})
    graph_evidence = {"schema_version": "qcb.cohort_source_graph.v1", "snapshot_id": snapshot["snapshot_id"],
                      "snapshot_source_commit": snapshot["commit"], "snapshot_path": rel(snapshot_path),
                      "snapshot_sha256": sha(snapshot_path), "new_lean_execution": False,
                      "selected_nodes": [graph[n] for n in selected],
                      "hyperedge_context_nodes": [graph[n] for n in context_ids],
                      "induced_navigation_edges": [e for e in snapshot["edges"] if e["source"] in selected and e["target"] in selected],
                      "conceptual_hyperedges_complete_tails_and_heads": hyperedges,
                      "sources": sources,
                      "limits": ["Node status is copied historical graph metadata, not newly checked status.",
                                 "Navigation/import/conceptual edges are not extracted proof-term dependencies.",
                                 "All conjunctive tails are retained; authored mathematical maps are in each QA payload.",
                                 "Original NL extensions are visibly identified in provenance; a graph anchor does not prove the extension.",
                                 "No live-library or branch-only node is inserted into the frozen snapshot."]}
    write(package / "evidence/source-graph-index.json", graph_evidence)
    graph_doc = ["# Source and graph evidence\n",
                 f"Snapshot `{snapshot['snapshot_id']}`, source commit `{snapshot['commit']}`; base `{BASE}`. "
                 "The exact selected nodes, unabridged relevant hyperedges, file hashes and use-specific source anchors are in `evidence/source-graph-index.json`.\n",
                 "| Evidence class | Meaning here |\n| --- | --- |",
                 "| Library declaration | A declaration present in frozen source text; its graph status is historical. No new Lean check ran. |",
                 "| Source-backed English derivation | The full proof is authored and reviewed in this cohort; generalized claims are not advertised as compiled library theorems. |",
                 "| Conceptual transport or planned material | A navigation/possibility record whose missing assumptions must be separately supplied and proved. |",
                 "| Branch-only work | Open PR evidence used for overlap and future compatibility; never current gold. |\n",
                 "| Selected node | Frozen kind | Frozen status |\n| --- | --- | --- |"]
    for n in selected:
        node = graph[n]
        graph_doc.append(f"| `{n}` | {cell(node.get('kind', ''))} | {cell(node.get('status', node.get('source_status', 'unspecified')))} |")
    graph_doc += ["\n| File | SHA-256 (raw bytes) |\n| --- | --- |"]
    graph_doc += [f"| `{r['path']}` | `{r['sha256_raw']}` |" for r in sources]
    graph_doc += ["\nSee `GRAPH_AND_REUSE.md` for actual shared subproofs and incompatible register/core orientations. "
                  "A checked proposition does not by itself yield a useful process reward or a valid arbitrary graph composition.\n"]
    (package / "SOURCE_AND_GRAPH.md").write_text("\n".join(graph_doc), encoding="utf-8")

    if args.manifest:
        if len(reports) != 3 or len(reviewed) != 12:
            raise ValueError("All three actual reviews are required for this final manifest.")
        files = sorted({p for p in package.rglob("*") if p.is_file() and p.name != "manifest.json"
                        and "__pycache__" not in p.parts} | set(proposals))
        manifest = {"schema_version": "qcb.nonlean_contribution_manifest.v1", "package_id": PACKAGE_ID,
                    "repository": "https://github.com/DakeBU/QuantumComputinglib-QuantumComputingBench",
                    "base_commit": BASE, "base_tree": "2ed1159e1973e65295c3e2a7dce73efc79244caf",
                    "working_branch": "codex/nonlean-cohort-20261103",
                    "snapshot_id": snapshot["snapshot_id"], "graph_source_commit": snapshot["commit"],
                    "snapshot_sha256": sha(snapshot_path), "catalog_hash": catalog["catalog_hash"],
                    "current_core_count_unchanged": len(catalog["cores"]),
                    "reserved_core_count_unchanged": len(catalog["withheld_cores"]),
                    "contribution_counts": dict(Counter(i["contribution_type"] for i in items)),
                    "new_cores_admitted": 0, "new_lean_execution": False,
                    "human_approval": False, "model_performance": "unmeasured",
                    "global_semantic_deduplication": "pending",
                    "contributions": contributions, "review_reports": reports,
                    "historical_review_records": [rel(package / "reviews/A-review-v1.json"),
                                                  rel(package / "reviews/B-review-v1.json")],
                    "pending_decisions": ["Candidate semantic equivalence and split reconciliation, especially B2 and PR114.",
                                          "Maintainer installation/admission of proposed views or candidates.",
                                          "Any future graph refresh and migration-specific source re-review.",
                                          "Finite-bit/physical-resource contracts beyond the supplied interfaces."],
                    "file_hash_policy": "SHA-256 of exact raw bytes; canonical item digests use qcb_core.digest. Manifest excludes itself to avoid recursive hashing; delivery SHA256SUMS binds it and the patch.",
                    "files": [{"path": rel(p), "sha256": sha(p), "bytes": p.stat().st_size} for p in files]}
        write(package / "manifest.json", manifest)
    print(json.dumps({"proposals_written": len(proposals), "source_files_indexed": len(sources),
                      "selected_graph_nodes": len(selected), "actual_review_items": len(reviewed),
                      "manifest_written": args.manifest, "admission": False}, indent=2))


if __name__ == "__main__":
    main()
